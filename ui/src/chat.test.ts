import assert from 'node:assert/strict';
import { test } from 'node:test';
import { JSDOM } from 'jsdom';
const dom = new JSDOM('<!doctype html><body></body>', {url:'http://localhost'});
const frames: FrameRequestCallback[] = [];
Object.assign(globalThis,{window:dom.window,document:dom.window.document,Node:dom.window.Node,requestAnimationFrame:(fn:FrameRequestCallback)=>{frames.push(fn);return 1;}});
(window as any).__TAURI_INTERNALS__={invoke:async(command:string)=>command==='chat_start'?'chat-test':[]};
const {chatPage,handleChatEvent}=await import('./pages/chat.ts');
const {ui}=await import('./state.ts');
const flush=()=>{for(const fn of frames.splice(0))fn(0);};
const options=(value:string)=>[{id:'model',name:'Model',category:'model',type:'select',value,choices:[{name:'A',value:'a'},{name:'B',value:'b'}]}];
test('streaming preserves composer, draft, focus and completed rows; model changes await acknowledgement',async()=>{
 ui.page='chat';ui.workspaces=[{id:'w',name:'Workspace',repo:'/repo',project_id:'',project_name:'',enabled:true}];
 document.body.append(chatPage());
 (document.querySelector('[data-act="chat-new"]') as HTMLElement).click();
 await new Promise(r=>setTimeout(r,0));document.body.replaceChildren(chatPage());
 handleChatEvent('chat-test',{ts:1,type:'ready',config_options:options('a')});flush();
 const input=document.querySelector<HTMLTextAreaElement>('#chat-input')!;
 input.value='Hello';input.dispatchEvent(new dom.window.Event('input'));
 input.dispatchEvent(new dom.window.KeyboardEvent('keydown',{key:'Enter',bubbles:true}));flush();
 const user=document.querySelector('#chat-scroll')!.firstElementChild;
 input.focus();input.value='draft';input.dispatchEvent(new dom.window.Event('input'));
 handleChatEvent('chat-test',{ts:2,type:'agent_message',text:'First'});flush();
 handleChatEvent('chat-test',{ts:3,type:'agent_message',text:' second'});flush();
 assert.equal(document.querySelector('#chat-input'),input);assert.equal(document.activeElement,input);assert.equal(input.value,'draft');
 assert.equal(document.querySelector('#chat-scroll')!.firstElementChild,user);
 assert.match(document.querySelector('#chat-scroll')!.textContent!,/First second/);
 handleChatEvent('chat-test',{ts:4,type:'turn_end'});flush();
 const picker=document.querySelector<HTMLSelectElement>('[data-category="model"]')!;
 picker.value='b';picker.dispatchEvent(new dom.window.Event('change'));flush();
 assert.equal(document.querySelector<HTMLSelectElement>('[data-category="model"]')!.disabled,true);
 assert.equal(document.querySelector<HTMLSelectElement>('[data-category="model"]')!.value,'a');
 handleChatEvent('chat-test',{ts:5,type:'config_options',options:options('b')});flush();
 assert.equal(document.querySelector<HTMLSelectElement>('[data-category="model"]')!.value,'b');
 assert.equal(document.querySelector<HTMLSelectElement>('[data-category="model"]')!.disabled,false);
});
